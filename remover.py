_PATTERN = re.compile(r"(" + "|".join(street_keywords) + r")", flags=re.IGNORECASE)
_WS = re.compile(r"\s+")
_TRAIL_COMMA = re.compile(r",\s*$")


def remove_street_info(address):
    match = _PATTERN.search(address)
    if match:
        keyword_pos = match.start() + 1
        comma_pos = address.rfind(",", 0, keyword_pos)
        if comma_pos != -1:
            address = address[:comma_pos]
        else:
            address = address[:keyword_pos]

    address = _WS.sub(" ", address).strip()
    address = _TRAIL_COMMA.sub("", address)

    return address
